#!/bin/sh
# Assembles the hxc haxelib package in bin/haxelib/hxc and zips it to
# bin/haxelib/hxc.zip (`haxelib install bin/haxelib/hxc.zip`, or `haxelib dev
# hxc bin/haxelib/hxc` while testing).
#
#   make haxelib        (or sh hxc/haxelib/build.sh)
#
# Package layout:
#   bin/hxc.com   the compiler (port + C backend) as a Cosmopolitan APE binary
#                 that runs on Linux, macOS, Windows and the BSDs (x86-64 and
#                 arm64), with the Haxe std subset in its own zip (/zip/std)
#   hxstd/        the class path: the hxc target's std overrides (bin/hxc/std)
#                 and hxc/{Boot,Build,Run}.hx (the init macro and `haxelib run hxc`)
#   rt/           the C runtime, compiled with the generated C on the user's machine
#   cosmo/        mbedtls and libuv built with cosmocc, for -D hxc.static
#                 (headers, fat static libraries; hxc/tools/deps.sh cosmo)
#   extraParams.hxml   --macro hxc.Boot.init(), added by -lib hxc
#
# The user's Haxe types the program and writes HXB; bin/hxc.com reads it
# (--hxb-lib) and lowers it to C. The archive's format must match the
# compiler hxc.com was built from (haxe/, see hxc.json).
#
# Needs: make, node, haxe/haxe (`make tool`), cosmocc on PATH (hxc/README.md, Cosmopolitan),
# git and patch (hxc/tools/deps.sh, once).
# The C is generated in chunks ($B/hxc_hxc/) and compiled in parallel, reusing
# unchanged objects (hxc/tools/cc-chunks.sh). SKIP_GEN=1 reuses the generated C, SKIP_COM=1 reuses the binary, NO_DEPS=1
# leaves mbedtls and libuv out (stubs that throw).
# NATIVE_CC=clang (or gcc, tcc...) builds a package for this machine only, without
# cosmocc: bin/hxc-native is compiled with "$NATIVE_CC -O2" (no mbedtls/libuv:
# macros run in the user's Haxe, the bundled Eval is not used for lowering) and
# bin/hxc.com is a shell script running it (Build.toC runs hxc.com with sh).
set -eu
cd "$(dirname "$0")/../.."
HAXE=${HAXE:-haxe/haxe}
B=bin/haxelib/build
P=bin/haxelib/hxc
mkdir -p "$B"

# bin/hxc/std (Makefile)
${MAKE:-make} HAXE="$HAXE" bin/hxc/std/.stamp
# 1. the backend tool (port + C backend) as C, generated by the JS build of itself
# (bin/hxc/wbk.js, `make tool`)
if [ -z "${SKIP_GEN:-}" ]; then
	${MAKE:-make} HAXE="$HAXE" bin/hxc/wbk.js
	HAXE_STD_PATH=$PWD/haxe/std node --stack-size=65500 bin/hxc/wbk.js "$B/hxc" \
		-cp src -cp hxc/src -cp hxc/js -cp bin/hxc/std -main backend.Main -D disable-parallelism \
		--custom-target hxc
fi

# 2. the APE binary. Macros run in the bundled Eval, whose sys.ssl and eval.luv
# use mbedtls and libuv built with cosmocc (hxc/tools/deps.sh, into
# $DEPS); NO_DEPS=1 builds without them (their natives fail when called)
DEPS=${COSMO_DEPS:-bin/deps/cosmo}
if [ -n "${NATIVE_CC:-}" ]; then
	NO_DEPS=1
	if [ -z "${SKIP_COM:-}" ] || [ ! -f "$B/hxc-native" ]; then
		CC="$NATIVE_CC -O2" CFLAGS="-w -fno-strict-aliasing -DHXC_CONST_IDS -DHXC_NO_SSL -DHXC_NO_UV" sh hxc/tools/cc-chunks.sh "$B/hxc_hxc" "$B/hxc-native"
	fi
elif [ -z "${NO_DEPS:-}" ]; then
	sh hxc/tools/deps.sh cosmo "$DEPS"
	RT="-I$DEPS/include"
	RT_LIBS="-L$DEPS/lib -lmbedtls -lmbedx509 -lmbedcrypto -luv"
else
	RT="-DHXC_NO_SSL -DHXC_NO_UV"
	RT_LIBS=
fi
if [ -n "${NATIVE_CC:-}" ]; then
	:
elif [ -z "${SKIP_COM:-}" ] || [ ! -f "$B/hxc.com" ]; then
	CC="cosmocc -O2" CFLAGS="-w -fno-strict-aliasing -DHXC_CONST_IDS $RT" LIBS="-lm $RT_LIBS" sh hxc/tools/cc-chunks.sh "$B/hxc_hxc" "$B/hxc.com"
fi

# 3. the package
rm -rf "$P" && mkdir -p "$P/bin" "$P/rt"
if [ -n "${NATIVE_CC:-}" ]; then
	cp "$B/hxc-native" "$P/bin/hxc-native"
	printf '#!/bin/sh\nexec "$(dirname "$0")/hxc-native" "$@"\n' > "$P/bin/hxc.com"
	chmod +x "$P/bin/hxc.com"
else
	cp "$B/hxc.com" "$P/bin/hxc.com"
	rm -rf "$B/std" && mkdir -p "$B/std"
	cp haxe/std/*.hx "$B/std/"
	cp -r haxe/std/haxe haxe/std/sys haxe/std/eval "$B/std/"
	(cd "$B" && zip -qr -9 "../../../$P/bin/hxc.com" std)
fi
# not std/: haxe looks for its own std in ./std, and haxelib runs Run.hx from the library root
cp -r bin/hxc/std "$P/hxstd"
cp -r hxc/haxelib/hxc/. "$P/hxstd/hxc/"
cp hxc/rt/*.h hxc/rt/rt*.c "$P/rt/"
# mbedtls and libuv for -D hxc.static with -D hxc.ssl / hxc.uv (headers and fat
# static libraries, about 1.6 MB zipped)
if [ -z "${NO_DEPS:-}" ]; then
	mkdir -p "$P/cosmo"
	cp -r "$DEPS/include" "$DEPS/lib" "$DEPS/VERSIONS" "$DEPS/LICENSE.mbedtls" "$DEPS/LICENSE.libuv" "$P/cosmo/"
fi
cp hxc/haxelib/haxelib.json hxc/haxelib/README.md hxc/haxelib/extraParams.hxml "$P/"
printf '{"haxe": "%s", "commit": "%s"}\n' "$("$HAXE" -version 2>&1)" "$(git -C haxe rev-parse --short HEAD)" > "$P/hxc.json"
cp haxe/LICENSE "$P/LICENSE.txt"
rm -f bin/haxelib/hxc.zip
(cd "$P" && zip -qr -9 ../hxc.zip .)
ls -l "$P/bin/hxc.com" bin/haxelib/hxc.zip
